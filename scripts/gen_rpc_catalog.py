#!/usr/bin/env python3
"""Generate Sources/MicropodAPI/HTTP2/RPCCatalog.generated.swift from proto/.

The gRPC transport answers UNIMPLEMENTED for a method no service declares
and needs to know which methods stream (a gRPC request carries no Connect
envelope hint). This reads every `service` in proto/micropod/v1/*.proto and
writes the table. It is kept outside Sources/MicropodCore/Generated, which
`buf generate` cleans.

    scripts/gen_rpc_catalog.py          # write the file
    scripts/gen_rpc_catalog.py --check  # exit 1 when it is stale
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROTO = ROOT / "proto" / "micropod" / "v1"
OUT = ROOT / "Sources" / "MicropodAPI" / "HTTP2" / "RPCCatalog.generated.swift"

COMMENT = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)
SERVICE = re.compile(r"\bservice\s+(\w+)\s*\{")
RPC = re.compile(r"\brpc\s+(\w+)\s*\(\s*(stream\s+)?[\w.]+\s*\)\s*returns\s*\(\s*(stream\s+)?[\w.]+\s*\)")


def services():
    found = {}
    for path in sorted(PROTO.glob("*.proto")):
        text = COMMENT.sub("", path.read_text())
        package = re.search(r"\bpackage\s+([\w.]+)\s*;", text).group(1)
        for match in SERVICE.finditer(text):
            depth, index = 1, match.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(text[index], 0)
                index += 1
            body = text[match.end():index]
            methods = {}
            for rpc in RPC.finditer(body):
                name, client_stream, server_stream = rpc.group(1), rpc.group(2), rpc.group(3)
                if client_stream:
                    kind = "bidiStream" if server_stream else "clientStream"
                else:
                    kind = "serverStream" if server_stream else "unary"
                methods[name] = kind
            found[f"{package}.{match.group(1)}"] = methods
    return found


def render(found):
    lines = [
        "// Generated by scripts/gen_rpc_catalog.py from proto/micropod/v1/*.proto. Do not edit.",
        "",
        "extension RPCCatalog {",
        "    static let services: [String: [String: RPCKind]] = [",
    ]
    for service in sorted(found):
        lines.append(f'        "{service}": [')
        for method in sorted(found[service]):
            lines.append(f'            "{method}": .{found[service][method]},')
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main():
    text = render(services())
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/gen_rpc_catalog.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
